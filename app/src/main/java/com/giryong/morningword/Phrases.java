    /** 같은 날에는 같은 문구가 나오도록 날짜로 고른 '오늘의 문구' 번호 */
    public static int todayIndex() {
        Calendar c = Calendar.getInstance();
        int key = c.get(Calendar.YEAR) * 400 + c.get(Calendar.DAY_OF_YEAR);
        return key % LIST.length;
    }

    /** 종류에 맞는 문구 중 하나를 무작위로 고른다(직전 문구는 피함). 번호를 돌려준다. */
    public static int randomIndex(String cat, int exclude, Random rnd) {
        List<Integer> pool = new ArrayList<>();
        for (int i = 0; i < LIST.length; i++) {
            if (ALL.equals(cat) || LIST[i][0].equals(cat)) pool.add(i);
        }
        if (pool.isEmpty()) return 0;
        if (pool.size() > 1) pool.remove(Integer.valueOf(exclude));
        return pool.get(rnd.nextInt(pool.size()));
    }
